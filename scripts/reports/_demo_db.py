def build(path: Path) -> None:
    connection = sqlite3.connect(path)
    connection.executescript(SCHEMA)
    for key, when, store, operation, prepaid, items in RECEIPTS:
        total = round(sum(item_sum for _, _, item_sum in items), 2)
        connection.execute(
            "insert into receipts values (?,?,?,?,?,?,?,?,?,?,?,NULL)",
            (
                key, "79000000001", None, "INDIVIDUAL", when, "1", "d" + key,
                store, "7700000001", when, str(abs(total)),
            ),
        )
        connection.execute(
            "insert into fiscal_data values (?,?,?,?,?,?,?,?,?)",
            (key, when, abs(total), operation, prepaid, store, "г. Москве", store, "7700000001"),
        )
        for idx, (name, quantity, item_sum) in enumerate(items, start=1):
            connection.execute(
                "insert into fiscal_data_items values (?,?,?,?,?,?,?,?,?,?)",
                (
                    key, idx, name, 10, 4,
                    round(abs(item_sum / quantity), 2) if quantity else 0,
                    1, None, quantity, item_sum,
                ),
            )
    connection.commit()
    connection.close()


if __name__ == "__main__":
    target = Path(sys.argv[1])
    target.unlink(missing_ok=True)
    build(target)
